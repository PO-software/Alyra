// Copies the Voting ABI from the backend's compiled artifact into a typed module.
// Run `pnpm hardhat build` in backend/ first, then `pnpm abi` here.
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const artifactPath = resolve(here, "../../backend/artifacts/contracts/Voting.sol/Voting.json")
const outputPath = resolve(here, "../src/contracts/votingAbi.ts")

if (!existsSync(artifactPath)) {
  console.error(`Artifact not found: ${artifactPath}\nRun \`pnpm hardhat build\` in backend/ first.`)
  process.exit(1)
}

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"))
const source =
  "// Generated by scripts/export-abi.mjs from backend/artifacts. Do not edit.\n" +
  `export const votingAbi = ${JSON.stringify(abi, null, 2)} as const\n`

writeFileSync(outputPath, source)
console.log(`Wrote ${abi.length} ABI entries to ${outputPath}`)
